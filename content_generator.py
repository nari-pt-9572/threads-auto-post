BEFORE_RULES = """- 投稿の最初から最後まで「手取り22万だった頃・お金がなかった頃」の視点のみで書く
- 「最近は〜」「今は〜」など現在の状況に切り替えるのは絶対にNG
- お金がなくて苦しかった場面・感情を、行動と具体的描写で伝える
- ネガティブで終わっていい（余韻が大事）"""

AFTER_RULES = """- 投稿の最初から最後まで「今・手取り30万になって余裕ができた状態」の視点のみで書く
- 過去の苦しさへの言及は1行以内の短い対比としてのみOK（主軸にしない）
- 副業・稼ぎ方の説明は絶対にしない（「変わった」「動いた」程度でOK）
- 自慢にならない・売り込み感ゼロ
- 余裕が生まれたことを、彼女のセリフや自分の行動の変化で自然に伝える"""


def generate_post(strategy: dict, topic: str, time_slot: str = "morning", post_type: str = "before", recent_posts: list = []) -> str:
    client = Groq(api_key=GROQ_API_KEY)

    keywords = "、".join(strategy.get("keywords", []))
    direction = strategy.get("strategy", "")

    if post_type == "after":
        examples = AFTER_EXAMPLES
        type_rules = AFTER_RULES
    else:
        examples = BEFORE_EXAMPLES
        type_rules = BEFORE_RULES

    # 直近投稿のネタ一覧（同じ場面・構成を避けるため）
    recent_texts = ""
    if recent_posts:
        recent_texts = "\n\n## 直近の投稿（以下と同じ場面・ネタ・書き出し・構成は絶対に使わないこと）\n"
        for p in recent_posts:
            text = p.get('text', '')
            first_line = text.split('\n')[0] if text else ''
            recent_texts += f"書き出し:「{first_line}」\n全文:{text[:100]}\n---\n"

    prompt = f"""以下の「良い投稿例」と全く同じ文体・構成・クオリティで投稿を1つ書いてください。

## 良い投稿例

{examples}

## 投稿のルール（全共通）
- 全体で170〜220文字【厳守】。170文字未満は失敗とみなす
- 最低8行以上書く（行数が足りない場合は場面・感情・行動の描写を追加する）
- 短すぎる場合は「その時の状況」「体の反応」「頭の中で考えていたこと」を1〜2行追加して補う
- 1文1行（改行必須）
- 1文は10〜30文字（短く、でも意味がある）
- 一人称は「僕」
- 絵文字なし・ハッシュタグなし
- 「同じような人いる？」などのCTAは入れない
- 売り込み感ゼロ

【最重要：彼女の一言を軸に設計する】
- 必ず「見た瞬間にスクロールが止まる彼女のセリフ」を1つ投稿に入れる
- そのセリフは「え、なんでそんなこと言われたの？」と思わせるものにする
- NG例：「ありがとう」「また来てね」「大丈夫」→ 日常すぎて引っかからない
- OK例（before）：「気にしないよ」「無理しなくていいよ」「私といると、しんどい？」「ちゃんと食べてる？」
- OK例（after）：「最近、別人みたい」「前と全然違う」「なんか余裕ある感じ」「何があったの？」
- セリフはその投稿の感情的クライマックスに置く（最後か後半）
- 投稿全体がそのセリフに向かって積み上がる構造にする
- セリフは最大2つまで。会話のやりとりが続くのはNG（劇になってしまうため）
- 「何も言えなかった」「何も言わなかった」などの同じ表現を繰り返さない
- 一人称「僕」に統一。「〜ません」「〜ました」などの丁寧語はNG

【読んで映像が浮かぶか？ が最重要】
- 全ての文が「誰が・どこで・何をしたか」を明確に描写していること
- 読んだ人が頭の中で場面を映像として想像できること
- 「え、どういう状況？」となる曖昧な描写はNG
- 主語が誰か、場所はどこか、行動は何か、を明確に書く

【1行目のフック】
- 毎回違うパターンで始める（場所・行動・セリフ・日時・金額など）
- 「財布に〇〇円しか」で始めるのは禁止（使いすぎ）
- 読んだ人が「続きを読みたい」と思う具体的な一言

【因果関係・ストーリーの一貫性】
- 前後の流れが論理的につながっていること
- セリフはその場面の感情を深めるものだけ使う（唐突なセリフNG）
- 感情は説明せず行動で見せる（「返信できなかった」「黙って運転してた」）

【設定・リアリティ】
- 移動手段は必ず「車」。電車・バス・徒歩で会いに行く描写は絶対にNG
- 距離は片道3時間（高速利用）。往復は最短6時間、下道なら8時間以上
- 「往復4時間」「往復5時間」など6時間未満の往復表現は絶対にNG
- 「往復10時間」「往復11時間」など8時間超の表現もNG
- afterで「早く会えるようになった」はNG。距離は変わらない。afterの変化はお金・気持ちの余裕のみ
- 交通費＝高速代＋ガソリン代。「電車賃」「バス代」はNG
- 「今夜会いに行く」など近距離前提の表現はNG
- 金額は社会人としてリアルな範囲で（数百円・1000円台はNG）

## このタイプの追加ルール
{type_rules}

## 今回のテーマ
{direction}
参考キーワード: {keywords}
{recent_texts}
投稿文だけ返してください（他は何も書かないこと）:"""

    response = client.chat.completions.create(
        model="llama-3.3-70b-versatile",
        messages=[{"role": "user", "content": prompt}],
        max_tokens=600,
        temperature=0.88,
    )

    return response.choices[0].message.content.strip()


def decide_post_type(posts_log: list) -> str:
    """
    直近の投稿履歴を見てbefore/afterを決める。
    - after連続OK
    - before/afterどちらでも新しいネタを優先
    - after比率は約40%
    - beforeが5連続したら強制的にafter
    """
    recent_types = [p.get("post_type", "before") for p in posts_log[-5:]]

    # beforeが5連続したらafterを強制
    if len(recent_types) >= 5 and all(t == "before" for t in recent_types):
        return "after"

    # 通常は60% before / 40% after
    return "after" if random.random() < 0.40 else "before"
